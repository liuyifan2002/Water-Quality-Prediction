from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import pandas as pd

from new_data_sources_utils import ROOT, date_tag_or_today, ensure_dir, experiment_dir, load_env_file, load_yaml_config, parse_date, sample_frame, write_json, write_markdown


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Prepare GEE ocean color extraction tasks for OLCI and related products.")
    parser.add_argument("--start-date", default="2014-01-01")
    parser.add_argument("--end-date", default="2024-12-31")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--out-dir", type=Path, default=None)
    parser.add_argument("--config", type=Path, default=None)
    parser.add_argument("--date-tag", default="20260516")
    parser.add_argument("--export-to-drive", action="store_true")
    parser.add_argument("--local", action="store_true")
    parser.add_argument("--station-asset-id", default="")
    parser.add_argument("--dataset-id-olci", default="")
    parser.add_argument("--dataset-id-kd490", default="")
    return parser.parse_args()


def build_js(sample_asset_id: str, olci_dataset: str, kd490_dataset: str, project: str) -> str:
    asset_line = sample_asset_id or "users/your-account/hk_station_date_samples"
    olci_line = olci_dataset or "COPERNICUS/PLACEHOLDER_OLCI_DATASET"
    kd_line = kd490_dataset or "COPERNICUS/PLACEHOLDER_KD490_DATASET"
    project_line = project or "your-ee-project"
    return f"""// Auto-generated by scripts/24_extract_gee_ocean_color_features.py
// Replace placeholder asset and dataset IDs before running in Earth Engine Code Editor.

var EE_PROJECT = '{project_line}';
var STATION_TABLE_ASSET = '{asset_line}';
var OLCI_DATASET_ID = '{olci_line}';
var KD490_DATASET_ID = '{kd_line}';
var WINDOW_BEFORE_DAYS = 3;
var WINDOW_AFTER_DAYS = 1;

var samples = ee.FeatureCollection(STATION_TABLE_ASSET);

function addWindow(feature) {{
  var sampleDate = ee.Date(feature.get('date'));
  return feature.set({{
    window_start: sampleDate.advance(-WINDOW_BEFORE_DAYS, 'day'),
    window_end: sampleDate.advance(WINDOW_AFTER_DAYS, 'day')
  }});
}}

var samplesWithWindow = samples.map(addWindow);

function computeIndices(image) {{
  var img = image.toFloat();
  var ndci = img.normalizedDifference(['Rrs_709', 'Rrs_665']).rename('olci_ndci');
  var mci = img.expression(
    'b709 - b681 - ((709 - 681) / (754 - 681)) * (b754 - b681)',
    {{
      b709: img.select('Rrs_709'),
      b681: img.select('Rrs_681'),
      b754: img.select('Rrs_754')
    }}
  ).rename('olci_mci');
  var fai = img.expression(
    'nir - (red + (swir - red) * ((865 - 665) / (1610 - 665)))',
    {{
      nir: img.select('Rrs_865'),
      red: img.select('Rrs_665'),
      swir: img.select('Rrs_1610')
    }}
  ).rename('olci_fai');
  return img.addBands([ndci, mci, fai]);
}}

function reduceSample(feature) {{
  var windowStart = ee.Date(feature.get('window_start'));
  var windowEnd = ee.Date(feature.get('window_end'));
  var point = ee.Geometry.Point([feature.getNumber('lon'), feature.getNumber('lat')]);
  var olci = ee.ImageCollection(OLCI_DATASET_ID)
    .filterDate(windowStart, windowEnd)
    .filterBounds(point)
    .map(computeIndices);
  var kd490 = ee.ImageCollection(KD490_DATASET_ID)
    .filterDate(windowStart, windowEnd)
    .filterBounds(point);

  var olciMedian = ee.Image(olci.median());
  var kdMedian = ee.Image(kd490.median());

  var olciStats = olciMedian.reduceRegion({{
    reducer: ee.Reducer.mean(),
    geometry: point.buffer(150),
    scale: 300,
    maxPixels: 1e8
  }});
  var kdStats = kdMedian.reduceRegion({{
    reducer: ee.Reducer.mean(),
    geometry: point.buffer(150),
    scale: 300,
    maxPixels: 1e8
  }});

  return feature.set(olciStats).set(kdStats);
}}

var extracted = samplesWithWindow.map(reduceSample);

Export.table.toDrive({{
  collection: extracted,
  description: 'hk_chla_new_sources_ocean_color',
  fileFormat: 'CSV'
}});
"""


def main() -> None:
    args = parse_args()
    config = load_yaml_config(args.config)
    env = load_env_file()
    date_tag = date_tag_or_today(args.date_tag)
    log_dir = ensure_dir(experiment_dir("chla_new_data_download", date_tag))
    out_dir = ensure_dir(args.out_dir or (ROOT / config["outputs"]["model_input_new_sources_dir"]))
    log_path = log_dir / "gee_ocean_color_extract_log.json"
    guide_path = log_dir / "gee_ocean_color_export_instructions.md"
    js_path = ROOT / "scripts" / "24_extract_gee_ocean_color_features.js"

    samples = sample_frame(config, args.start_date, args.end_date)
    station_asset_id = args.station_asset_id or config.get("gee", {}).get("station_asset_id", "")
    ee_project = env.get(config.get("gee", {}).get("project_env_var", "EARTHENGINE_PROJECT"), "")
    olci_dataset = args.dataset_id_olci
    kd490_dataset = args.dataset_id_kd490

    js_path.write_text(build_js(station_asset_id, olci_dataset, kd490_dataset, ee_project), encoding="utf-8")

    report: dict[str, Any] = {
        "label": "GEE 海洋水色提取准备",
        "dry_run": args.dry_run,
        "sample_rows": int(len(samples)),
        "start_date": args.start_date,
        "end_date": args.end_date,
        "station_asset_id": station_asset_id,
        "earthengine_project_present": bool(ee_project),
        "dataset_id_olci": olci_dataset,
        "dataset_id_kd490": kd490_dataset,
        "script_path": str(js_path),
        "output_dir": str(out_dir),
        "standardized_outputs": [
            str(out_dir / "sentinel3_olci_features_2014_2024.csv"),
            str(out_dir / "ocean_color_kd490_tss_features_2014_2024.csv"),
        ],
    }

    if args.dry_run:
        report["status"] = "dry_run_only"
        write_json(log_path, report)
        write_markdown(
            guide_path,
            "GEE 海洋水色导出说明",
            [
                "1. 已生成 GEE JS 脚本，请先把 `data/model_input/gee_station_date_samples.csv` 上传为 GEE 表资产。",
                f"2. 脚本位置：`{js_path}`。",
                "3. 将 `STATION_TABLE_ASSET`、`OLCI_DATASET_ID`、`KD490_DATASET_ID` 替换为实际值后，在 Earth Engine Code Editor 运行。",
                "4. 真实导出完成后，将 CSV 标准化为 `data/model_input/new_sources/sentinel3_olci_features_2014_2024.csv` 和 `ocean_color_kd490_tss_features_2014_2024.csv`。",
            ],
        )
        print("Dry-run only. Generated GEE JS scaffold and export instructions.")
        return

    if not ee_project:
        report["status"] = "missing_earthengine_project"
        write_json(log_path, report)
        raise RuntimeError("未检测到 EARTHENGINE_PROJECT，请在 .env 或系统环境变量中配置。")

    if not station_asset_id:
        report["status"] = "missing_station_asset"
        write_json(log_path, report)
        raise RuntimeError("未提供 GEE 站点资产 ID，无法直接执行导出。")

    if not olci_dataset or not kd490_dataset:
        report["status"] = "missing_dataset_id"
        write_json(log_path, report)
        raise RuntimeError("缺少 OLCI 或 KD490 数据集 ID。请在命令参数中提供。")

    try:
        import ee  # type: ignore

        ee.Initialize(project=ee_project)
        report["earthengine_initialize"] = "ok"
    except Exception as exc:
        report["status"] = "earthengine_auth_failed"
        report["error"] = f"{type(exc).__name__}: {exc}"
        write_json(log_path, report)
        raise RuntimeError("Earth Engine 未认证或项目不可用。请先完成 `earthengine authenticate`。") from exc

    report["status"] = "prepared_for_code_editor_export"
    report["message"] = "当前脚本已完成本地认证检查，但 station-date 大表仍建议通过 GEE Code Editor 批量导出。"
    write_json(log_path, report)
    write_markdown(
        guide_path,
        "GEE 海洋水色导出说明",
        [
            "1. 本地 Earth Engine 认证已通过，但当前流程仍建议在 GEE Code Editor 执行大表导出。",
            f"2. 打开 [24_extract_gee_ocean_color_features.js]({js_path}) 并运行导出任务。",
            "3. 导出完成后，将 CSV 归档到 `data/model_input/new_sources/`，再执行 `python scripts/21_validate_new_chla_data_sources.py --date-tag 20260516`。",
        ],
    )
    print("Earth Engine authentication succeeded. Use the generated JS script in Code Editor for bulk export.")


if __name__ == "__main__":
    main()
