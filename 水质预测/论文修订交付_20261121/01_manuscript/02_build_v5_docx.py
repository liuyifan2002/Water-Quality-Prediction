def replace(p, s, why='正文定点修订'):
    old=p.text
    if old==s:return
    assert p._p.getparent() is not None
    p.clear();p.add_run(s)
    changes.append({'原段':old[:150], '新段':s[:150], '原因':why})

def remove(p):
    e=p._p
    if e.getparent() is not None:e.getparent().remove(e)

def after(anchor,s='',style='Normal'):
    e=OxmlElement('w:p');anchor._p.addnext(e)
    p=Paragraph(e,doc._body);p.style=style;p.add_run(s)
    return p

